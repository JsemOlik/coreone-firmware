#!/usr/bin/env python3
# Generate klippy/extras/display/font_aa.py, the anti-aliased fonts of the
# ili9488 graphical UI, from the DejaVu TrueType fonts
#
# Usage: gen_aa_fonts.py <dejavu font dir> <output file>
# Needs Pillow. The DejaVu fonts are under the Bitstream Vera license.
#
