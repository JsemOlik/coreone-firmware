import sys, os, base64
from PIL import Image, ImageDraw, ImageFont

ASCII = ''.join(chr(c) for c in range(0x20, 0x7f)) + '\xb0\xb7'
DIGITS = '0123456789 .-+%/:\xb0C'

# name: (ttf file, pixel size, characters)
FONTS = [
    ('small', 'DejaVuSans.ttf', 16, ASCII),
    ('normal', 'DejaVuSans.ttf', 21, ASCII),
    ('bold', 'DejaVuSans-Bold.ttf', 21, ASCII),
    ('large', 'DejaVuSans-Bold.ttf', 40, DIGITS),
]

def render_font(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    for ch in chars:
        width = max(1, int(round(font.getlength(ch))))
        img = Image.new('L', (width, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        px = img.tobytes()
        # Two pixels per byte, high nibble first, rows padded to a byte
        data = bytearray()
        for y in range(height):
            row = [(px[y * width + x] + 8) // 17 for x in range(width)]
            if width & 1:
                row.append(0)
            for x in range(0, len(row), 2):
                data.append((row[x] << 4) | row[x + 1])
        glyphs.append((ch, width, bytes(data)))
    return height, ascent, glyphs

def main():
    fontdir, outname = sys.argv[1], sys.argv[2]
    out = ["# Anti-aliased fonts of the ili9488 graphical UI",
           "#",
           "# Generated by scripts/gen_aa_fonts.py from the DejaVu fonts",
           "# (Bitstream Vera license) - do not edit.",
           "#",
           "# This file may be distributed under the terms of the GNU GPLv3"
           " license.",
           "",
           "# name: (height, ascent, characters, widths, 4bpp bitmaps)",
           "FONTS = {"]
    for name, ttf, size, chars in FONTS:
        height, ascent, glyphs = render_font(
            os.path.join(fontdir, ttf), size, chars)
        widths = bytes(w for ch, w, d in glyphs)
        blob = base64.b64encode(b''.join(d for ch, w, d in glyphs)).decode()
        out.append("    %r: (%d, %d, %r, %r," % (
            name, height, ascent, ''.join(chars), widths))
        lines = [blob[i:i + 72] for i in range(0, len(blob), 72)]
        out.append("        \"\"\"" + lines[0])
        out.extend(lines[1:])
        out[-1] += "\"\"\"),"
    out.append("}")
    with open(outname, 'w') as f:
        f.write("\n".join(out) + "\n")

if __name__ == '__main__':
    main()
